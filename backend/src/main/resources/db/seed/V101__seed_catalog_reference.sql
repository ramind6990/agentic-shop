-- categories, level by level, then materialized paths
insert into category (parent_id, name, slug, level, path, sort_order, is_leaf, description)
select null, c.name, c.slug, 0, '/', c.sort, false, c.description
from seed.cat c where c.parent is null;

insert into category (parent_id, name, slug, level, path, sort_order, is_leaf, description)
select p.id, c.name, c.slug, 1, '/', c.sort, false,
       coalesce(c.description, 'Browse ' || lower(c.name) || ' from independent sellers.')
from seed.cat c join category p on p.slug = c.parent and p.level = 0;

insert into category (parent_id, name, slug, level, path, sort_order, is_leaf, description)
select p.id, c.name, c.slug, 2, '/', c.sort, true,
       coalesce(c.description, 'Shop ' || lower(c.name) || ' from independent sellers.')
from seed.cat c join category p on p.slug = c.parent and p.level = 1;

update category set path = '/' || id || '/' where level = 0;
update category c set path = p.path || c.id || '/' from category p where c.parent_id = p.id and c.level = 1;
update category c set path = p.path || c.id || '/' from category p where c.parent_id = p.id and c.level = 2;

-- attributes
insert into attribute_definition (code, name, data_type, unit, min_value, max_value, step_value)
select a.code, a.name, a.data_type, a.unit,
       case when a.data_type = 'NUMBER' then (select min(v::numeric) from seed.cat_attr ca, unnest(ca.vals) v where ca.code = a.code) end,
       case when a.data_type = 'NUMBER' then (select max(v::numeric) from seed.cat_attr ca, unnest(ca.vals) v where ca.code = a.code) end,
       null
from seed.attr a
order by a.code;

-- options: every ENUM value used by any category, in first-seen order
insert into attribute_option (attribute_id, value, label, sort_order)
select ad.id, v.val,
       coalesce(o.label, initcap(replace(v.val, '_', ' '))),
       (row_number() over (partition by ad.id order by v.first_seen))::int
from (
    select ca.code, x.val, min(ca.id * 100 + x.ord) as first_seen
    from seed.cat_attr ca, unnest(ca.vals) with ordinality as x(val, ord)
    group by ca.code, x.val
) v
join attribute_definition ad on ad.code = v.code and ad.data_type in ('ENUM', 'MULTI_ENUM')
left join seed.attr_opt o on o.code = v.code and o.value = v.val;

insert into category_attribute (category_id, attribute_id, filterable, sort_order)
select c.id, ad.id, ca.filterable, (row_number() over (partition by c.id order by ca.id))::int
from seed.cat_attr ca
join category c on c.slug = ca.cat
join attribute_definition ad on ad.code = ca.code;

-- brands
insert into brand (name, slug, description)
select distinct n, seed.slugify(n), null
from seed.brand_scope bs, unnest(bs.names) n;

update brand b set description = b.name || ' makes ' || lower(c.name) || ' sold by independent retailers on AgenticShop.'
from seed.brand_scope bs join category c on c.slug = bs.cat
where b.name = any (bs.names);

-- brand -> leaf categories it can appear in
create table seed.brand_leaf as
select b.id as brand_id, leaf.id as leaf_id
from seed.brand_scope bs
join category scope on scope.slug = bs.cat
join category leaf on leaf.is_leaf and leaf.path like scope.path || '%'
join brand b on b.name = any (bs.names);

create index on seed.brand_leaf (leaf_id);
