-- ai agent: run traces, the token usage ledger, and the new reply envelope shape.

-- One run of a conversation (the graph from the user's message to its reply), kept after the active run row is gone.
-- A paused run is PAUSED until it is resumed (RUNNING again), abandoned or finished. Prunable with its conversation.
create table ai_run (
    id               uuid         primary key,
    conversation_id  bigint       not null references ai_conversation (id) on delete cascade,
    user_id          bigint       not null references app_user (id),
    status           varchar(16)  not null check (status in
                         ('RUNNING', 'PAUSED', 'COMPLETED', 'FAILED', 'CANCELLED', 'ABANDONED')),
    prompt_version   varchar(40),
    model            varchar(80),
    started_at       timestamptz  not null,
    updated_at       timestamptz  not null,
    finished_at      timestamptz,
    step_count       int          not null default 0,
    error_code       varchar(60),
    error_message    text
);

create index ix_ai_run_conversation on ai_run (conversation_id, started_at);
create index ix_ai_run_user on ai_run (user_id, started_at);

-- What happened inside a run, in order: the user's input, every model attempt (retries included), every executed
-- tool, rejected model outputs, the question or approval it paused on, the reply or the error. Debug data.
create table ai_run_step (
    id                   bigint generated by default as identity primary key,
    run_id               uuid          not null references ai_run (id) on delete cascade,
    seq                  int           not null,
    step_type            varchar(16)   not null check (step_type in
                             ('INPUT', 'MODEL', 'TOOL', 'VALIDATION', 'INTERACTION', 'REPLY', 'ERROR')),
    name                 varchar(120)  not null,
    -- MODEL: 1 for the first try, 2.. for retries
    attempt              int,
    args_summary         text,
    result_summary       text,
    error_code           varchar(60),
    latency_ms           int,
    input_tokens         int,
    cached_input_tokens  int,
    output_tokens        int,
    reasoning_tokens     int,
    created_at           timestamptz   not null,
    constraint uq_ai_run_step unique (run_id, seq)
);

-- Append-only token ledger: one row per successful model call. issuer USER = calls answering the user's message,
-- SYSTEM = work the system does on its own (e.g. summarizing the conversation's memory). Rows are never updated.
create table ai_usage (
    id                   bigint generated by default as identity primary key,
    user_id              bigint        references app_user (id),
    conversation_id      bigint        references ai_conversation (id) on delete set null,
    run_id               uuid          references ai_run (id) on delete set null,
    issuer               varchar(16)   not null check (issuer in ('USER', 'SYSTEM')),
    purpose              varchar(20)   not null check (purpose in ('CHAT', 'SUMMARY')),
    provider             varchar(40)   not null,
    model                varchar(80)   not null,
    input_tokens         int           not null default 0,
    cached_input_tokens  int           not null default 0,
    output_tokens        int           not null default 0,
    reasoning_tokens     int           not null default 0,
    created_at           timestamptz   not null
);

create index ix_ai_usage_user on ai_usage (user_id, created_at);
create index ix_ai_usage_conversation on ai_usage (conversation_id, id);
create index ix_ai_usage_run on ai_usage (run_id);

-- Stored reply envelopes: the item list moves into a typed "block" ({type, items}); blockType is gone.
update ai_conversation_message
set reply = (reply - 'productList' - 'blockType')
            || jsonb_build_object('block', jsonb_build_object('type', 'PRODUCT_LIST', 'items', reply -> 'productList'))
where reply ? 'productList';

update ai_conversation_message
set reply = (reply - 'orderList' - 'blockType')
            || jsonb_build_object('block', jsonb_build_object('type', 'ORDER_LIST', 'items', reply -> 'orderList'))
where reply ? 'orderList';

update ai_conversation_message set reply = reply - 'blockType' where reply ? 'blockType';
