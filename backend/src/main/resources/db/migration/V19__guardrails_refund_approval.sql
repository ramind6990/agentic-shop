alter table ai2_run_step drop constraint ai2_run_step_step_type_check;
alter table ai2_run_step add constraint ai2_run_step_step_type_check check (step_type in
    ('INPUT', 'MODEL', 'TOOL', 'VALIDATION', 'GUARD', 'INTERACTION', 'REPLY', 'ERROR'));

alter table ai2_usage drop constraint ai2_usage_purpose_check;
alter table ai2_usage add constraint ai2_usage_purpose_check check (purpose in ('CHAT', 'SUMMARY', 'GUARD'));

-- Four-eyes refunds: a staff member asks for a refund above their own limit; a colleague whose limit covers it
-- approves it (the refund is issued then, with the approver as issuer) or rejects it. Never the requester themself.
create table refund_approval (
    id                 bigint generated by default as identity primary key,
    approval_number    varchar(30)    not null unique,
    order_id           bigint         not null references customer_order (id),
    return_request_id  bigint references return_request (id),
    amount             numeric(12, 2) not null check (amount > 0),
    reason             varchar(200)   not null,
    status             varchar(20)    not null check (status in ('PENDING', 'APPROVED', 'REJECTED')),
    -- the lowest role whose limit covers the amount (SUPPORT_T2 or FINANCE)
    approver_role      varchar(20)    not null,
    requested_by_id    bigint         not null references app_user (id),
    requested_at       timestamptz    not null,
    decided_by_id      bigint references app_user (id),
    decided_at         timestamptz,
    decision_note      varchar(500),
    refund_id          bigint references refund (id),
    ticket_id          bigint references ticket (id),
    idempotency_key    varchar(80) unique,
    constraint chk_refund_approval_four_eyes check (decided_by_id is null or decided_by_id <> requested_by_id)
);

create index idx_refund_approval_queue on refund_approval (status, approver_role);
create index idx_refund_approval_order on refund_approval (order_id, status);
create index idx_refund_approval_requester on refund_approval (requested_by_id);
