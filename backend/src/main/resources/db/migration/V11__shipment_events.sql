-- Tracking: carrier scans of each shipment, and the carrier's estimated delivery date

alter table shipment add column estimated_delivery date;

create table shipment_event (
    id           bigint generated by default as identity primary key,
    shipment_id  bigint       not null references shipment (id),
    occurred_at  timestamptz  not null,
    type         varchar(30)  not null,
    location     varchar(120),
    description  varchar(240) not null
);

create index idx_shipment_event_shipment on shipment_event (shipment_id, occurred_at);
create index idx_shipment_tracking_number on shipment (tracking_number);
