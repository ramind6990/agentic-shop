-- Catalog: category tree, brands, EAV attributes, products, inventory, reviews come later (need orders)

create table category (
    id          bigint generated by default as identity primary key,
    parent_id   bigint references category (id),
    name        varchar(120) not null,
    slug        varchar(140) not null unique,
    level       smallint     not null,
    path        varchar(255) not null,
    sort_order  integer      not null default 0,
    is_leaf     boolean      not null default false,
    description text
);

create table brand (
    id          bigint generated by default as identity primary key,
    name        varchar(120) not null unique,
    slug        varchar(140) not null unique,
    description text
);

create table attribute_definition (
    id          bigint generated by default as identity primary key,
    code        varchar(60)  not null unique,
    name        varchar(120) not null,
    data_type   varchar(20)  not null,
    unit        varchar(20),
    min_value   numeric(12, 2),
    max_value   numeric(12, 2),
    step_value  numeric(12, 2)
);

create table attribute_option (
    id            bigint generated by default as identity primary key,
    attribute_id  bigint       not null references attribute_definition (id),
    value         varchar(80)  not null,
    label         varchar(120) not null,
    sort_order    integer      not null default 0,
    unique (attribute_id, value)
);

create table category_attribute (
    id            bigint generated by default as identity primary key,
    category_id   bigint  not null references category (id),
    attribute_id  bigint  not null references attribute_definition (id),
    filterable    boolean not null default true,
    sort_order    integer not null default 0,
    unique (category_id, attribute_id)
);

create table product (
    id            bigint generated by default as identity primary key,
    seller_id     bigint        not null references seller (id),
    category_id   bigint        not null references category (id),
    brand_id      bigint        not null references brand (id),
    sku           varchar(40)   not null unique,
    title         varchar(300)  not null,
    slug          varchar(340)  not null,
    description   text          not null,
    price         numeric(12, 2) not null,
    list_price    numeric(12, 2),
    currency      varchar(3)       not null default 'USD',
    status        varchar(20)   not null,
    rating_avg    numeric(3, 2),
    rating_count  integer       not null default 0,
    sales_count   integer       not null default 0,
    created_at    timestamptz   not null,
    updated_at    timestamptz   not null
);

create table product_image (
    id          bigint generated by default as identity primary key,
    product_id  bigint       not null references product (id),
    url         varchar(400) not null,
    alt_text    varchar(300),
    sort_order  integer      not null default 0
);

create table product_attribute_value (
    id            bigint generated by default as identity primary key,
    product_id    bigint not null references product (id),
    attribute_id  bigint not null references attribute_definition (id),
    option_id     bigint references attribute_option (id),
    number_value  numeric(12, 2),
    bool_value    boolean
);

create table inventory (
    product_id      bigint primary key references product (id),
    qty_available   integer     not null,
    qty_reserved    integer     not null default 0,
    warehouse_code  varchar(20) not null,
    restock_eta     date
);
