-- RAG: embedded chunks of policy document versions, with the ACL and validity metadata needed to filter retrieval
-- in SQL. Written only by ai.rag.PolicyIngestionService (manual reindex); see PolicyChunkStore for how the ACL
-- filter uses the columns. A chunk never crosses a document_section, because sections carry their own min_role.

create table ai_policy_chunk (
    id                   bigint generated by default as identity primary key,
    document_id          bigint        not null references document (id) on delete cascade,
    document_version_id  bigint        not null references document_version (id) on delete cascade,
    -- null only for a version without sections (its summary is chunked instead)
    section_id           bigint references document_section (id) on delete cascade,
    doc_code             varchar(80)   not null,
    doc_type             varchar(30)   not null,
    -- ACL, copied from the source rows at ingestion time:
    --   seller_id          document.seller_id   (tenant document: its own seller sees every section)
    --   doc_min_role       document.min_role
    --   section_min_role   document_section.min_role (= doc_min_role for a summary chunk)
    seller_id            bigint,
    doc_min_role         varchar(20)   not null,
    section_min_role     varchar(20)   not null,
    -- validity of the version: effective_from <= day < effective_to (open-ended when null)
    version_no           integer       not null,
    version_label        varchar(20)   not null,
    effective_from       date          not null,
    effective_to         date,
    doc_title            varchar(200)  not null,
    section_heading      varchar(200),
    -- "<doc title> > <section heading>", the citation path
    heading_path         varchar(420)  not null,
    section_ordinal      integer,
    chunk_index          integer       not null,
    -- the chunk body as it appears in the source (what a citation quotes)
    text                 text          not null,
    char_count           integer       not null,
    -- approximate (chars / 4) size of the embedded text, which is the body prefixed with title/version/heading
    token_count          integer       not null,
    -- sha-256 of embedded text + model + dimensions: unchanged hash = embedding reused
    content_hash         char(64)      not null,
    embedding            vector(1536)  not null,
    embedding_model      varchar(80)   not null,
    tsv                  tsvector generated always as (
                             to_tsvector('english', coalesce(heading_path, '') || ' ' || text)) stored,
    created_at           timestamptz   not null default now(),
    updated_at           timestamptz   not null default now(),
    constraint uq_ai_policy_chunk unique nulls not distinct (document_version_id, section_id, chunk_index)
);

create index ix_ai_policy_chunk_embedding on ai_policy_chunk using hnsw (embedding vector_cosine_ops);
create index ix_ai_policy_chunk_tsv on ai_policy_chunk using gin (tsv);
create index ix_ai_policy_chunk_version on ai_policy_chunk (document_version_id);
create index ix_ai_policy_chunk_acl on ai_policy_chunk (doc_min_role, section_min_role, doc_type);
create index ix_ai_policy_chunk_seller on ai_policy_chunk (seller_id) where seller_id is not null;
create index ix_ai_policy_chunk_effective on ai_policy_chunk (effective_from, effective_to);
