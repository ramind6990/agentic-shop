-- ai2 agent: conversations, their chat messages and their memory (summary of older messages).

create table ai2_conversation (
    id          bigint generated by default as identity primary key,
    user_id     bigint       not null references app_user (id),
    -- CLOSED: the conversation's memory hit its hard limit; new messages are refused
    status      varchar(16)  not null check (status in ('OPEN', 'CLOSED')),
    created_at  timestamptz  not null,
    updated_at  timestamptz  not null
);

create index ix_ai2_conversation_user on ai2_conversation (user_id, updated_at desc);

-- runs and checkpoints now belong to a conversation; earlier rows have none and are transient anyway
delete from ai2_active_run;
alter table ai2_active_run
    add constraint fk_ai2_active_run_conversation
        foreign key (conversation_id) references ai2_conversation (id) on delete cascade;
alter table ai2_checkpoint add column conversation_id bigint not null;
alter table ai2_checkpoint
    add constraint fk_ai2_checkpoint_conversation
        foreign key (conversation_id) references ai2_conversation (id) on delete cascade;

-- The chat timeline. USER: the customer's text. ASSISTANT: the reply (payload = AgentResponse, display = the shown
-- tool result: full data for the UI + agent summary for the history). INTERACTION: a question or approval the run
-- paused on (payload = the pending interaction), with its status and the customer's answer.
create table ai2_conversation_message (
    id                  bigint generated always as identity primary key,
    conversation_id     bigint       not null references ai2_conversation (id) on delete cascade,
    run_id              uuid,
    kind                varchar(16)  not null check (kind in ('USER', 'ASSISTANT', 'INTERACTION')),
    text                text,
    payload             jsonb,
    display             jsonb,
    interaction_id      uuid unique,
    interaction_status  varchar(16) check (interaction_status in
                            ('PENDING', 'ANSWERED', 'DISMISSED', 'APPROVED', 'DENIED', 'NOT_ANSWERED')),
    answer              jsonb,
    created_at          timestamptz  not null,
    updated_at          timestamptz  not null,
    check ((kind = 'INTERACTION') = (interaction_id is not null and interaction_status is not null))
);

create index ix_ai2_message_conversation on ai2_conversation_message (conversation_id, id);

-- The summary of a conversation's older messages: every message up to summarized_through_message_id is folded in.
create table ai2_conversation_memory (
    conversation_id                bigint       primary key references ai2_conversation (id) on delete cascade,
    summary                        text         not null,
    summarized_through_message_id  bigint       not null,
    updated_at                     timestamptz  not null
);
