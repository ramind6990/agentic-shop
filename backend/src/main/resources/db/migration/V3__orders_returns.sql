-- Orders (one order = one seller), payments, shipments, returns, refunds, reviews

create table customer_order (
    id                bigint generated by default as identity primary key,
    order_number      varchar(30)    not null unique,
    customer_id       bigint         not null references app_user (id),
    seller_id         bigint         not null references seller (id),
    status            varchar(30)    not null,
    ship_recipient    varchar(160)   not null,
    ship_line1        varchar(200)   not null,
    ship_line2        varchar(200),
    ship_city         varchar(100)   not null,
    ship_region       varchar(100),
    ship_postal_code  varchar(20)    not null,
    ship_country      varchar(2)        not null,
    subtotal          numeric(12, 2) not null,
    shipping_fee      numeric(12, 2) not null,
    tax               numeric(12, 2) not null,
    total             numeric(12, 2) not null,
    currency          varchar(3)        not null default 'USD',
    placed_at         timestamptz    not null
);

create table order_item (
    id             bigint generated by default as identity primary key,
    order_id       bigint         not null references customer_order (id),
    product_id     bigint         not null references product (id),
    product_title  varchar(300)   not null,
    sku            varchar(40)    not null,
    unit_price     numeric(12, 2) not null,
    quantity       integer        not null,
    line_total     numeric(12, 2) not null
);

create table payment (
    id            bigint generated by default as identity primary key,
    order_id      bigint         not null references customer_order (id),
    method        varchar(20)    not null,
    status        varchar(20)    not null,
    amount        numeric(12, 2) not null,
    provider_ref  varchar(60)    not null,
    created_at    timestamptz    not null
);

create table shipment (
    id               bigint generated by default as identity primary key,
    order_id         bigint      not null references customer_order (id),
    carrier          varchar(20) not null,
    tracking_number  varchar(40) not null,
    status           varchar(20) not null,
    shipped_at       timestamptz,
    delivered_at     timestamptz
);

create table return_request (
    id              bigint generated by default as identity primary key,
    order_id        bigint      not null references customer_order (id),
    order_item_id   bigint      not null references order_item (id),
    customer_id     bigint      not null references app_user (id),
    quantity        integer     not null,
    reason          varchar(30) not null,
    status          varchar(20) not null,
    customer_note   text,
    seller_note     text,
    opened_at       timestamptz not null,
    resolved_at     timestamptz
);

create table refund (
    id                 bigint generated by default as identity primary key,
    order_id           bigint         not null references customer_order (id),
    return_request_id  bigint references return_request (id),
    amount             numeric(12, 2) not null,
    reason             varchar(200)   not null,
    status             varchar(20)    not null,
    issued_by_id       bigint references app_user (id),
    idempotency_key    varchar(80) unique,
    created_at         timestamptz    not null
);

create table review (
    id             bigint generated by default as identity primary key,
    product_id     bigint       not null references product (id),
    customer_id    bigint       not null references app_user (id),
    order_item_id  bigint references order_item (id),
    rating         smallint     not null check (rating between 1 and 5),
    title          varchar(200) not null,
    body           text         not null,
    helpful_count  integer      not null default 0,
    created_at     timestamptz  not null
);
