-- Support tickets and fraud/risk flags

create table ticket (
    id             bigint generated by default as identity primary key,
    ticket_number  varchar(30)  not null unique,
    customer_id    bigint       not null references app_user (id),
    order_id       bigint references customer_order (id),
    seller_id      bigint references seller (id),
    assignee_id    bigint references app_user (id),
    subject        varchar(240) not null,
    category       varchar(20)  not null,
    status         varchar(20)  not null,
    priority       varchar(20)  not null,
    tier           varchar(5)   not null,
    created_at     timestamptz  not null,
    updated_at     timestamptz  not null
);

create table ticket_message (
    id           bigint generated by default as identity primary key,
    ticket_id    bigint      not null references ticket (id),
    author_id    bigint references app_user (id),
    author_type  varchar(20) not null,
    body         text        not null,
    internal     boolean     not null default false,
    created_at   timestamptz not null,
    -- shape of the message: TEXT, or a structured payload (agent envelope or action detail)
    kind           varchar(20) not null default 'TEXT',
    payload        jsonb,
    schema_version int
);

create table account_flag (
    id             bigint generated by default as identity primary key,
    subject_type   varchar(20)   not null,
    subject_id     bigint        not null,
    flag_type      varchar(30)   not null,
    risk_score     numeric(5, 2) not null,
    note           text          not null,
    created_by_id  bigint references app_user (id),
    active         boolean       not null default true,
    created_at     timestamptz   not null
);
