-- AI support-agent core: structured ticket messages, run trace, usage ledger, chat actions.

-- Ticket messages gain a kind and an optional structured payload (agent envelope or action detail).
-- author_type has no check constraint, so the new AI author needs no DDL change.
alter table ticket_message
    add column kind           varchar(20) not null default 'TEXT',
    add column payload        jsonb,
    add column schema_version int;

-- One agent turn.
create table ai_run (
    id              uuid primary key,
    ticket_id       bigint references ticket (id),
    user_id         bigint       not null references app_user (id),
    status          varchar(20)  not null,
    prompt_version  varchar(40),
    model           varchar(80),
    started_at      timestamptz  not null,
    finished_at     timestamptz,
    step_count      int          not null default 0,
    error_code      varchar(60),
    error_message   text
);

create index ix_ai_run_ticket_started on ai_run (ticket_id, started_at);
create index ix_ai_run_user_started on ai_run (user_id, started_at);

-- Debug trace of model and tool steps within a run. Prunable.
create table ai_step (
    id              bigint generated by default as identity primary key,
    run_id          uuid         not null references ai_run (id) on delete cascade,
    seq             int          not null,
    step_type       varchar(20)  not null,
    name            varchar(120) not null,
    args_summary    text,
    result_summary  text,
    error_code      varchar(60),
    latency_ms      int,
    input_tokens    int,
    output_tokens   int,
    created_at      timestamptz  not null,
    constraint uq_ai_step_run_seq unique (run_id, seq)
);

-- Price per 1M tokens, versioned by effective_from.
create table ai_model_price (
    id               bigint generated by default as identity primary key,
    provider         varchar(40)    not null,
    model            varchar(80)    not null,
    token_type       varchar(20)    not null,
    usd_per_million  numeric(12, 6) not null,
    effective_from   timestamptz    not null,
    constraint uq_ai_model_price unique (provider, model, token_type, effective_from)
);

