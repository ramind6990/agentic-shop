-- Append-only billing ledger. Rows are never updated.
create table ai_usage (
    id                     bigint generated by default as identity primary key,
    user_id                bigint references app_user (id),
    ticket_id              bigint references ticket (id),
    run_id                 uuid references ai_run (id),
    purpose                varchar(20)    not null,
    provider               varchar(40)    not null,
    model                  varchar(80)    not null,
    input_tokens           int            not null default 0,
    cached_input_tokens    int            not null default 0,
    output_tokens          int            not null default 0,
    cost_usd               numeric(14, 8) not null,
    input_price_id         bigint references ai_model_price (id),
    cached_input_price_id  bigint references ai_model_price (id),
    output_price_id        bigint references ai_model_price (id),
    partial                boolean        not null default false,
    created_at             timestamptz    not null
);

create index ix_ai_usage_user_created on ai_usage (user_id, created_at);
create index ix_ai_usage_ticket_created on ai_usage (ticket_id, created_at);
create index ix_ai_usage_run on ai_usage (run_id);

-- A clickable action or confirmation offered in the chat. Only the SHA-256 of the token is stored.
create table ai_action (
    id                     bigint generated by default as identity primary key,
    token_hash             varchar(64)  not null unique,
    ticket_id              bigint       not null references ticket (id),
    message_id             bigint references ticket_message (id),
    user_id                bigint       not null references app_user (id),
    action_type            varchar(30)  not null,
    target_type            varchar(30),
    target_id              bigint,
    params                 jsonb,
    requires_confirmation  boolean      not null,
    state                  varchar(20)  not null,
    outcome                varchar(20),
    outcome_detail         text,
    expires_at             timestamptz  not null,
    created_at             timestamptz  not null,
    used_at                timestamptz
);

create index ix_ai_action_ticket_state on ai_action (ticket_id, state);
create index ix_ai_action_target_state on ai_action (target_type, target_id, state);
create index ix_ai_action_message on ai_action (message_id);
