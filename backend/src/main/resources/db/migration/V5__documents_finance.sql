-- Document corpora (versioned, with ACL metadata) and seller finance (contracts, payouts)

create table document (
    id          bigint generated by default as identity primary key,
    code        varchar(80)  not null unique,
    type        varchar(30)  not null,
    title       varchar(200) not null,
    min_role    varchar(20)  not null,
    seller_id   bigint references seller (id)
);

create table document_version (
    id              bigint generated by default as identity primary key,
    document_id     bigint      not null references document (id),
    version_no      integer     not null,
    effective_from  date        not null,
    effective_to    date,
    summary         text,
    unique (document_id, version_no)
);

create table document_section (
    id          bigint generated by default as identity primary key,
    version_id  bigint       not null references document_version (id),
    ordinal     integer      not null,
    heading     varchar(200) not null,
    body        text         not null,
    min_role    varchar(20)  not null
);

create table seller_contract (
    id                  bigint generated by default as identity primary key,
    seller_id           bigint         not null references seller (id),
    document_id         bigint references document (id),
    fee_plan            varchar(20)    not null,
    commission_rate     numeric(5, 4)  not null,
    per_order_fee       numeric(8, 2)  not null,
    monthly_fee         numeric(8, 2)  not null,
    return_window_days  integer        not null,
    effective_from      date           not null,
    effective_to        date
);

create table payout (
    id                 bigint generated by default as identity primary key,
    seller_id          bigint         not null references seller (id),
    period_start       date           not null,
    period_end         date           not null,
    order_count        integer        not null,
    gross_sales        numeric(14, 2) not null,
    commission_amount  numeric(14, 2) not null,
    fees_amount        numeric(14, 2) not null,
    refunds_amount     numeric(14, 2) not null,
    net_amount         numeric(14, 2) not null,
    status             varchar(20)    not null,
    paid_at            timestamptz
);
